import mysql from 'mysql2/promise';
import dotenv from 'dotenv';
dotenv.config();

const cfg = {
  host: process.env.DB_HOST || 'localhost',
  port: Number(process.env.DB_PORT) || 3306,
  user: process.env.DB_USER || 'root',
  password: process.env.DB_PASSWORD || '',
};
export const DB_NAME = process.env.DB_NAME || 'imenu_console';

export let pool: mysql.Pool;

/** Create the database and tables if needed (safe to run on every start). */
export async function initDb() {
  const boot = await mysql.createConnection(cfg);
  await boot.query(`CREATE DATABASE IF NOT EXISTS \`${DB_NAME}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci`);
  await boot.end();
  pool = mysql.createPool({ ...cfg, database: DB_NAME, charset: 'utf8mb4', timezone: '+00:00', connectionLimit: 10 });
  (pool as any).pool.on('connection', (c: any) => c.query("SET time_zone = '+00:00'", () => {}));

  await pool.query(`CREATE TABLE IF NOT EXISTS customers (
    id INT AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    code VARCHAR(40) NOT NULL UNIQUE,          -- enrolment code typed on a new device to attach it
    notes TEXT NULL,
    is_active TINYINT(1) NOT NULL DEFAULT 1,
    licence_until DATE NULL,                    -- NULL = no expiry
    features JSON NULL,                         -- {"reports": false, ...}; missing = on
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
  ) ENGINE=InnoDB`);
  await pool.query(`CREATE TABLE IF NOT EXISTS devices (
    id INT AUTO_INCREMENT PRIMARY KEY,
    install_id VARCHAR(64) NOT NULL UNIQUE,     -- random id generated by the app on first start
    android_id VARCHAR(64) NULL,                -- ANDROID_ID as reported by the device
    serial VARCHAR(80) NULL,                    -- physical S/N label, typed by you in the panel
    label VARCHAR(120) NULL,
    brand VARCHAR(60) NULL,
    model VARCHAR(80) NULL,
    platform VARCHAR(30) NULL,
    os_version VARCHAR(40) NULL,
    app_version VARCHAR(30) NULL,
    customer_id INT NULL,
    status ENUM('pending','allowed','blocked') NOT NULL DEFAULT 'allowed',
    licence_until DATE NULL,                    -- overrides the customer's date when set
    features JSON NULL,                         -- per-device overrides, win over the customer's
    last_ip VARCHAR(64) NULL,
    first_seen_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_seen_at TIMESTAMP NULL,
    notes TEXT NULL,
    INDEX (customer_id),
    CONSTRAINT fk_dev_cust FOREIGN KEY (customer_id) REFERENCES customers(id) ON DELETE SET NULL
  ) ENGINE=InnoDB`);

  // Customer detail columns, added to databases created by the first version.
  const cols: [string, string][] = [
    ['business_id', 'VARCHAR(40) NULL'], ['contact_name', 'VARCHAR(120) NULL'], ['phone', 'VARCHAR(40) NULL'],
    ['phone2', 'VARCHAR(40) NULL'], ['email', 'VARCHAR(160) NULL'], ['address', 'VARCHAR(200) NULL'],
    ['city', 'VARCHAR(80) NULL'], ['country', 'VARCHAR(60) NULL'], ['website', 'VARCHAR(160) NULL'],
  ];
  for (const [name, def] of cols) {
    const [r] = await pool.query<any[]>(
      'SELECT 1 FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = ? AND TABLE_NAME = ? AND COLUMN_NAME = ?', [DB_NAME, 'customers', name]);
    if (!r.length) await pool.query(`ALTER TABLE customers ADD COLUMN ${name} ${def}`);
  }

  // First start: create one customer so the very first device has somewhere to appear.
  const [n] = await pool.query<any[]>('SELECT COUNT(*) AS n FROM customers');
  if (!n[0].n) {
    await pool.query('INSERT INTO customers (name, code) VALUES (?, ?)',
      [process.env.CONSOLE_FIRST_CUSTOMER || 'My first customer', (process.env.CONSOLE_FIRST_CODE || 'FIRST').toUpperCase()]);
  }
}
